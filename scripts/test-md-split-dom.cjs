// Exercise the built webview and real DOM events without touching user documents.
const { JSDOM, VirtualConsole } = require('jsdom');
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const provider = fs.readFileSync(path.join(root, 'src/mdEditorProvider.ts'), 'utf8');
const template = provider.match(/return `\s*(<!DOCTYPE html>[\s\S]*?<\/html>)`;/)?.[1];
if (!template) throw new Error('Markdown provider template not found');
const html = template.replace(/\$\{\w+\}/g, '').replace(/<script[^>]*src="[^"]*"[^>]*><\/script>/g, '');
const errors = [];
const virtualConsole = new VirtualConsole();
virtualConsole.on('jsdomError', error => errors.push(error.message));
const dom = new JSDOM(html, { url: 'http://localhost/', runScripts: 'dangerously', pretendToBeVisual: true, virtualConsole });
const w = dom.window;
w.TextEncoder = TextEncoder; w.TextDecoder = TextDecoder;
w.ResizeObserver = class { observe() {} unobserve() {} disconnect() {} };
w.IntersectionObserver = class { observe() {} unobserve() {} disconnect() {} };
w.matchMedia = () => ({ matches: false, addListener() {}, removeListener() {}, addEventListener() {}, removeEventListener() {} });
w.scrollTo = () => {};
const messages = [];
w.acquireVsCodeApi = () => ({ postMessage: message => messages.push(message), getState: () => ({}), setState: () => {} });
w.eval(fs.readFileSync(path.join(root, 'dist/md/mdWebview.js'), 'utf8'));
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
(async () => {
    await wait(100);
    w.postMessage({ command: 'initSettings', settings: { stickyToolbar: true, wordWrap: true, syncScroll: true, previewPosition: 'right', language: 'zh' } }, '*');
    w.postMessage({ command: 'initMarkdown', content: 'hello world\n' }, '*');
    await wait(100);
    w.document.getElementById('toggleEditModeButton').click();
    await wait(100);
    const preview = w.document.getElementById('markdownPreview');
    const editor = w.document.getElementById('markdownEditor');
    if (preview.contentEditable !== 'true') throw new Error('Split preview is not editable on entry');
    const paragraph = preview.querySelector('p');
    if (!paragraph) throw new Error('Preview paragraph is missing');
    paragraph.textContent = 'hello changed';
    paragraph.dispatchEvent(new w.Event('input', { bubbles: true }));
    await wait(400);
    if (editor.value !== 'hello changed\n') throw new Error('Preview edit did not sync to source');
    editor.value = 'source side\n';
    editor.dispatchEvent(new w.Event('input', { bubbles: true }));
    await wait(650);
    if (!preview.textContent.includes('source side')) throw new Error('Source edit did not update preview');
    w.document.getElementById('saveEditsButton').click();
    const save = messages.filter(message => message.command === 'saveMarkdown').at(-1);
    if (!save || save.text !== 'source side\n') throw new Error('Save request did not contain the edited source');
    w.postMessage({ command: 'saveResult', ok: true }, '*');
    await wait(100);
    w.document.getElementById('toggleEditModeButton').click();
    await wait(100);
    const fenced = 'before\n\n```js\nconst a=1;\n```\n';
    editor.value = fenced;
    editor.dispatchEvent(new w.Event('input', { bubbles: true }));
    await wait(650);
    if (preview.contentEditable !== 'false' || editor.value !== fenced) throw new Error('Fenced source was not protected');
    if (errors.length) throw new Error(errors.join('; '));
    console.log('分屏 DOM 测试通过：入口可编辑、双向同步、围栏代码原文保护。');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => dom.window.close());
