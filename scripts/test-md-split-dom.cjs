// Exercise the built webview and real DOM events without touching user documents.
const { JSDOM, VirtualConsole } = require('jsdom');
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const provider = fs.readFileSync(path.join(root, 'src/mdEditorProvider.ts'), 'utf8');
const template = provider.match(/return `\s*(<!DOCTYPE html>[\s\S]*?<\/html>)`;/)?.[1];
if (!template) throw new Error('Markdown provider template not found');
const html = template.replace(/\$\{\w+\}/g, '').replace(/<script[^>]*src="[^"]*"[^>]*><\/script>/g, '');
const errors = [];
const virtualConsole = new VirtualConsole();
virtualConsole.on('jsdomError', error => errors.push(error.message));
const dom = new JSDOM(html, { url: 'http://localhost/', runScripts: 'dangerously', pretendToBeVisual: true, virtualConsole });
const w = dom.window;
w.TextEncoder = TextEncoder; w.TextDecoder = TextDecoder;
w.ResizeObserver = class { observe() {} unobserve() {} disconnect() {} };
w.IntersectionObserver = class { observe() {} unobserve() {} disconnect() {} };
w.matchMedia = () => ({ matches: false, addListener() {}, removeListener() {}, addEventListener() {}, removeEventListener() {} });
w.scrollTo = () => {};
const messages = [];
w.acquireVsCodeApi = () => ({ postMessage: message => messages.push(message), getState: () => ({}), setState: () => {} });
w.eval(fs.readFileSync(path.join(root, 'dist/md/mdWebview.js'), 'utf8'));
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
(async () => {
    await wait(100);
    w.postMessage({ command: 'initSettings', settings: { stickyToolbar: true, wordWrap: true, syncScroll: true, previewPosition: 'right', language: 'zh' } }, '*');
    w.postMessage({ command: 'initMarkdown', content: 'hello world\n' }, '*');
    await wait(100);
    w.document.getElementById('toggleEditModeButton').click();
    await wait(100);
    const preview = w.document.getElementById('markdownPreview');
    const editor = w.document.getElementById('markdownEditor');
    if (preview.contentEditable !== 'true') throw new Error('Split preview is not editable on entry');
    const paragraph = preview.querySelector('p');
    if (!paragraph) throw new Error('Preview paragraph is missing');
    paragraph.textContent = 'hello changed';
    paragraph.dispatchEvent(new w.Event('input', { bubbles: true }));
    await wait(400);
    if (editor.value !== 'hello changed\n') throw new Error('Preview edit did not sync to source');
    editor.value = 'source side\n';
    editor.dispatchEvent(new w.Event('input', { bubbles: true }));
    await wait(650);
    if (!preview.textContent.includes('source side')) throw new Error('Source edit did not update preview');
    w.document.getElementById('saveEditsButton').click();
    const save = messages.filter(message => message.command === 'saveMarkdown').at(-1);
    if (!save || save.text !== 'source side\n') throw new Error('Save request did not contain the edited source');
    w.postMessage({ command: 'saveResult', ok: true }, '*');
    await wait(100);
    w.document.getElementById('toggleEditModeButton').click();
    await wait(100);
    const fenced = 'before\n\n```js\nconst a=1;\n```\n';
    editor.value = fenced;
    editor.dispatchEvent(new w.Event('input', { bubbles: true }));
    await wait(650);
    if (preview.contentEditable !== 'true' || editor.value !== fenced) throw new Error('Fenced document cannot enter safe preview editing');
    const fenceNode = preview.querySelector('.code-block');
    if (!fenceNode || fenceNode.getAttribute('contenteditable') !== 'false') throw new Error('Code block must remain protected');
    const before = preview.querySelector('p');
    before.textContent = 'changed';
    before.dispatchEvent(new w.Event('input', { bubbles: true }));
    await wait(400);
    if (editor.value !== 'changed\n\n```js\nconst a=1;\n```\n') throw new Error('Preview edit changed fenced code source');
    const unusualFence = 'intro\n\n~~~~js  title\n\tconst x = `ok`;\n\n~~~~\n\nend\n';
    editor.value = unusualFence;
    editor.dispatchEvent(new w.Event('input', { bubbles: true }));
    await wait(650);
    if (preview.contentEditable !== 'true') throw new Error('Tabs inside a fenced block should remain safe');
    const intro = preview.querySelector('p');
    intro.textContent = 'edited';
    intro.dispatchEvent(new w.Event('input', { bubbles: true }));
    await wait(400);
    if (editor.value !== unusualFence.replace('intro', 'edited')) throw new Error('Preview edit altered unusual fenced source');
    w.document.getElementById('saveEditsButton').click();
    const savedFenced = messages.filter(message => message.command === 'saveMarkdown').at(-1);
    if (!savedFenced || savedFenced.text !== unusualFence.replace('intro', 'edited')) throw new Error('Save request altered fenced source');
    w.postMessage({ command: 'saveResult', ok: true }, '*');
    await wait(100);
    w.document.getElementById('toggleEditModeButton').click();
    await wait(100);
    const twoBlocks = 'start\n\n```\none\n```\n\nmiddle\n\n~~~python\ntwo\n~~~\n\nend\n';
    editor.value = twoBlocks;
    editor.dispatchEvent(new w.Event('input', { bubbles: true }));
    await wait(650);
    if (preview.contentEditable !== 'true' || preview.querySelectorAll('.code-block').length !== 2) throw new Error('Multiple fences were not safely rendered');
    preview.querySelector('p').textContent = 'edited';
    preview.querySelector('p').dispatchEvent(new w.Event('input', { bubbles: true }));
    await wait(400);
    if (editor.value !== twoBlocks.replace('start', 'edited')) throw new Error('Multiple fenced blocks were not preserved');
    const diagram = 'caption\n\n```mermaid\ngraph TD\n  A-->B\n```\n';
    editor.value = diagram;
    editor.dispatchEvent(new w.Event('input', { bubbles: true }));
    await wait(650);
    if (preview.contentEditable !== 'true' || !preview.querySelector('.mermaid')) throw new Error('Mermaid source was not safely rendered');
    preview.querySelector('p').textContent = 'changed';
    preview.querySelector('p').dispatchEvent(new w.Event('input', { bubbles: true }));
    await wait(400);
    if (editor.value !== diagram.replace('caption', 'changed')) throw new Error('Mermaid source was not preserved');
    const unsafeTabs = 'one\ttwo\n';
    editor.value = unsafeTabs;
    editor.dispatchEvent(new w.Event('input', { bubbles: true }));
    await wait(650);
    if (preview.contentEditable !== 'false' || editor.value !== unsafeTabs) throw new Error('Tabs outside fences must remain protected');
    if (errors.length) throw new Error(errors.join('; '));
    console.log('分屏 DOM 测试通过：双向同步，含代码块文档可编辑正文且代码原文不变。');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => dom.window.close());
